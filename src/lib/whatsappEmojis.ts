/** Converte um valor armazenado (legado ou emoji) para o emoji exibido. */
export function normalizeReactionEmoji(raw: string | null | undefined): string {
  if (!raw) return '👍';
  return LEGACY_REACTION_TO_EMOJI[raw] ?? raw;
}
